"""Metadata validation uses the actual C1717 palette snapshot, no provider I/O."""
import copy
import unittest
from types import SimpleNamespace
from app.modules.image_orchestrator import admission as a,policy as p,print_box

ART="a"*64
SOURCE="b"*64


def fixture():
    colors=list(a.PALETTE)[:9]
    lock={**print_box.FIXED,"artwork_sha256":ART,"placement_side":"front_center",
          "print_width_mm":191.16,"width_source":"sms_preview_advisory","ink_aspect_ratio":1.25}
    lock["lock_sha256"]=print_box.lock_digest(lock)
    plan={"skillSha256":p.SKILL_SHA256,"garmentSku":"C1717",
          "artworkSha256":ART,"sourceSha256":SOURCE,"storagePlacement":"front",
          "placementLock":lock,"mockupSize":"M","smsAdvisoryWidthMm":169.34,"paletteSha256":a.PALETTE_SHA,
          "roleColors":{**{f"{n:02d}":colors[0] for n in range(1,5)},
                         **{f"{n:02d}":colors[n-4] for n in range(5,13)}},
          "infographicSwatches":colors[1:9],"infographicSourceRoles":[1,5,6,7]}
    pack=SimpleNamespace(garment_sku="C1717",skill_sha256=p.SKILL_SHA256,
        artwork_sha256=ART,source_sha256=SOURCE,placement_sha256=lock["lock_sha256"],
        plan_sha256=p.canonical_sha(plan))
    return plan,pack


class AdmissionTests(unittest.TestCase):
    def test_valid_pinned_palette_and_placement_metadata(self):
        plan,pack=fixture()
        result=a.validate_plan(plan,pack)
        self.assertEqual(len(result["alternateColorIds"]),8)
        self.assertFalse(result["physicalCalibrationVerified"])
        self.assertEqual(result["placementLock"]["print_width_mm"],191.16)
        self.assertEqual(result["smsProductionMaxWidthMm"],279.4)
        self.assertEqual(result["printBoxAuthority"],print_box.AUTHORITY)

    def test_exact_extension_js_lock_digest(self):
        plan,pack=fixture()
        # Generated by the actual installed Bridge createPrintPlacementV3
        # with bounds [0,0,999,799] and source SHA "a"*64.
        expected="4e093b15b7913630ed3167e5d5fec8f96350476f41582cd849242b232b5852f2"
        self.assertEqual(pack.placement_sha256,expected)
        self.assertEqual(a.validate_plan(plan,pack)["placementLock"]["lock_sha256"],expected)

    def test_width_is_locked_not_recomputed_from_advisory(self):
        plan,pack=fixture()
        plan["smsAdvisoryWidthMm"]=169.34
        pack.plan_sha256=p.canonical_sha(plan)
        self.assertEqual(a.validate_plan(plan,pack)["placementLock"]["print_width_mm"],191.16)
        plan["placementLock"]["print_width_mm"]=169.34
        pack.plan_sha256=p.canonical_sha(plan)
        with self.assertRaisesRegex(p.Conflict,"placement_lock_unverified"):
            a.validate_plan(plan,pack)

    def test_real_factory_max_and_unknown_size_fail_closed(self):
        plan,pack=fixture()
        plan["placementLock"]["print_width_mm"]=300
        plan["placementLock"]["lock_sha256"]=print_box.lock_digest(plan["placementLock"])
        pack.placement_sha256=plan["placementLock"]["lock_sha256"]
        pack.plan_sha256=p.canonical_sha(plan)
        with self.assertRaisesRegex(p.Conflict,"print_box_exceeds_sms_factory_limit"):
            a.validate_plan(plan,pack)
        plan,pack=fixture();del plan["mockupSize"]
        pack.plan_sha256=p.canonical_sha(plan)
        with self.assertRaisesRegex(p.Conflict,"sms_production_limit_unverified"):
            a.validate_plan(plan,pack)

    def test_lock_or_palette_changes_rejected_even_with_new_plan_hash(self):
        for key,value in (("top_offset_mm",100),("top_offset_tolerance_mm",10),
                          ("shared_placement_across_roles",False)):
            plan,pack=fixture();plan["placementLock"][key]=value
            plan["placementLock"]["lock_sha256"]=print_box.lock_digest(plan["placementLock"])
            pack.placement_sha256=plan["placementLock"]["lock_sha256"]
            pack.plan_sha256=p.canonical_sha(plan)
            with self.assertRaisesRegex(p.Conflict,"placement_lock_unverified"):
                a.validate_plan(plan,pack)
        plan,pack=fixture();plan["paletteSha256"]="f"*64
        pack.plan_sha256=p.canonical_sha(plan)
        with self.assertRaisesRegex(p.Conflict,"palette_revision_changed"):
            a.validate_plan(plan,pack)

    def test_color_drift_duplicate_and_unconfigured_rejected(self):
        for role,color,code in (("03",list(a.PALETTE)[1],"base_color_drift"),
             ("06",list(a.PALETTE)[1],"duplicate_colorway"),
             ("08","paprika","unconfigured_pilot_color")):
            plan,pack=fixture();plan["roleColors"][role]=color
            pack.plan_sha256=p.canonical_sha(plan)
            with self.assertRaisesRegex(p.Conflict,code):
                a.validate_plan(plan,pack)

    def test_exact_current_native_master_and_source_binding(self):
        _,pack=fixture()
        selected=SimpleNamespace(state="saved",digest=ART,position="front",
                                  job_id="job-fixture",asset_id="asset-fixture")
        asset={"id":"asset-fixture","output_sha256":ART,"artwork_kind":"native_master_v2",
               "method":"imagegen","position":"front","position_verified":True,
               "source_sha256":SOURCE,"storage_provider":"google_drive_managed",
               "drive_file_id":"drive_original_fixture"}
        row=SimpleNamespace(id="job-fixture",status="completed",cancellation_requested=False,
                            payload_json={"design_assets":[asset]})
        result=a.validate_selected_asset(selected,[row],pack)
        self.assertFalse(result["originalBytesVerified"])
        self.assertFalse(result["sourceVisualQaVerified"])
        for key,value in (("source_sha256","f"*64),("position_verified",False),
                          ("artwork_kind","print_png_v1")):
            bad=copy.deepcopy(row);bad.payload_json["design_assets"][0][key]=value
            with self.assertRaisesRegex(p.Conflict,"source_asset_unverified"):
                a.validate_selected_asset(selected,[bad],pack)
        selected.digest="f"*64
        with self.assertRaisesRegex(p.Conflict,"current_artwork_unverified"):
            a.validate_selected_asset(selected,[row],pack)
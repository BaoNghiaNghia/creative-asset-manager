def compose_review_text(*, analysis_id: str, embroidery_visible: bool) -> str:
    """Build stable synthetic review copy with deliberately varied cadence and length."""
    digest = hashlib.sha256(("review-copy:" + analysis_id).encode("utf-8")).digest()
    length_bucket = digest[0] % 100
    short_pool = _REVIEW_SHORT_EMBROIDERY if embroidery_visible else _REVIEW_SHORT_GENERIC
    detail_pool = _REVIEW_EMBROIDERY_DETAILS if embroidery_visible else _REVIEW_GENERIC_DETAILS

    if length_bucket < 25:
        return short_pool[digest[1] % len(short_pool)]

    opening = _REVIEW_OPENINGS[digest[1] % len(_REVIEW_OPENINGS)]
    detail = detail_pool[digest[2] % len(detail_pool)]
    if length_bucket < 75:
        return f"{opening} {detail}"

    closing = _REVIEW_CLOSINGS[digest[3] % len(_REVIEW_CLOSINGS)]
    return f"{opening} {detail} {closing}"


def review_text_for_analysis(
    document: Stage3UgcAnalysisDocument,
    analysis_id: str,
) -> str:
    # Gemini still returns a short review observation as part of structured
    # analysis, but final customer-facing copy is composed locally. This keeps
    # wording stable across refreshes and prevents repeated model openers from
    # propagating across an entire review grid.
    return compose_review_text(
        analysis_id=analysis_id,
        embroidery_visible=document.embroidery_visible,
    )


class RrugcStage3Service:
    def __init__(self, session: Session):
        self.session = session

    def get_analysis(
        self, tenant_id: str, stage2_job_id: str
    ) -> RrugcStage3AnalysisModel | None:
        return self.session.scalar(
            select(RrugcStage3AnalysisModel).where(
                RrugcStage3AnalysisModel.tenant_id == tenant_id,
                RrugcStage3AnalysisModel.stage2_job_id == stage2_job_id,
            )
        )

    def ensure_analysis_for_job(
        self,
        *,
        tenant_id: str,
        stage2_job: RrugcStage2JobModel,
        force: bool = False,
    ) -> tuple[RrugcStage3AnalysisModel, bool]:
        if (
            stage2_job.tenant_id != tenant_id
            or stage2_job.status != "completed"
            or not stage2_job.output_remote_file_id
        ):
            raise ValueError("Stage 2 output is not eligible for Stage 3 analysis.")

        row = self.get_analysis(tenant_id, stage2_job.id)
        created = row is None
        now = datetime.now(timezone.utc)
        if row is None:
            row = RrugcStage3AnalysisModel(
                tenant_id=tenant_id,
                stage2_job_id=stage2_job.id,
                output_content_hash=stage2_job.output_content_hash,
                analysis_version=STAGE3_ANALYSIS_VERSION,
                analysis_revision=1,
                status="queued",
                queued_at=now,
            )
            self.session.add(row)
            self.session.flush()
        else:
            output_changed = (
                row.output_content_hash != stage2_job.output_content_hash
                or row.analysis_version != STAGE3_ANALYSIS_VERSION
            )
            if not force and not output_changed and row.status in {
                "queued",
                "analyzing",
                "ready",
                "rejected",
            }:
                return row, False
            row.analysis_revision = max(1, int(row.analysis_revision or 0) + 1)
            row.output_content_hash = stage2_job.output_content_hash
            row.analysis_version = STAGE3_ANALYSIS_VERSION
            row.status = "queued"
            row.queued_at = now
            row.started_at = None
            row.completed_at = None
            row.reviewer_name = None
            row.star_rating = None
            row.review_text = None
            row.review_generated_at = None
            row.last_error_code = None
            row.last_error_message = None

        processing_job, processing_created = ProcessingRepository(self.session).create_job_once(
            tenant_id=tenant_id,
            job_type=STAGE3_JOB_TYPE,
            entity_type="rrugc_stage3_analysis",
            entity_id=row.id,
            idempotency_key=(
                f"rrugc-stage3-analyze:{row.id}:{row.analysis_revision}"
            ),
            payload={
                "analysis_id": row.id,
                "stage2_job_id": stage2_job.id,
                "analysis_revision": row.analysis_revision,
            },
            priority=15,
            max_attempts=4,
        )
        row.processing_job_id = processing_job.id
        self.session.flush()
        return row, bool(created or processing_created)


class RrugcStage3AnalyzeJobHandler:
    def __call__(self, context: JobHandlerContext) -> JobHandlerResult:
        try:
            return asyncio.run(self._execute(context))
        except ValidationError as exc:
            context.logger.warning(
                "rrugc_stage3_analysis_invalid_document",
                extra={
                    "analysis_id": context.job.entity_id,
                    "tenant_id": context.job.tenant_id,
                    "validation_errors": exc.errors(include_input=False),
                },
            )
            self._mark_error(
                context,
                "stage3_analysis_invalid_document",
                "Stage 3 analyzer returned an invalid document.",
            )
            return JobHandlerResult.retryable(
                "stage3_analysis_invalid_document",
                "Stage 3 analyzer returned an invalid document.",
            )
        except AnalysisImageError as exc:
            self._mark_error(context, exc.code, str(exc))
            outcome = (
                JobHandlerResult.retryable
                if exc.retryable
                else JobHandlerResult.non_retryable
            )
            return outcome(exc.code, str(exc))
        except StorageProviderError as exc:
            self._mark_error(context, exc.code, "Stage 3 image could not be opened.")
            outcome = (
                JobHandlerResult.retryable
                if exc.retryable
                else JobHandlerResult.non_retryable
            )
            return outcome(exc.code, "Stage 3 image could not be opened.")
        except AiProviderUnavailableError:
            self._mark_error(
                context,
                "ai_provider_unavailable",
                "Stage 3 analyzer provider is unavailable.",
            )
            return JobHandlerResult.non_retryable(
                "ai_provider_unavailable",
                "Stage 3 analyzer provider is unavailable.",
            )
        except AiProviderError as exc:
            self._mark_error(context, exc.code, "Stage 3 analyzer failed.")
            deferred = deferred_rrugc_ai_retry(
                exc,
                message="Stage 3 analyzer is temporarily unavailable.",
            )
            if deferred is not None:
                return deferred
            outcome = (
                JobHandlerResult.retryable
                if exc.retryable
                else JobHandlerResult.non_retryable
            )
            return outcome(exc.code, "Stage 3 analyzer failed.")
        except Exception:
            context.logger.exception(
                "rrugc_stage3_analysis_failed",
                extra={
                    "analysis_id": context.job.entity_id,
                    "tenant_id": context.job.tenant_id,
                },
            )
            self._mark_error(
                context,
                "stage3_analysis_internal_error",
                "Stage 3 analysis failed.",
            )
            return JobHandlerResult.retryable(
                "stage3_analysis_internal_error",
                "Stage 3 analysis failed.",
            )

    async def _execute(self, context: JobHandlerContext) -> JobHandlerResult:
        analysis_id = str(context.job.payload.get("analysis_id") or "")
        stage2_job_id = str(context.job.payload.get("stage2_job_id") or "")
        revision = context.job.payload.get("analysis_revision")
        if (
            not analysis_id
            or analysis_id != context.job.entity_id
            or not stage2_job_id
            or not isinstance(revision, int)
        ):
            return JobHandlerResult.non_retryable(
                "stage3_analysis_job_invalid",
                "Stage 3 analysis job payload is invalid.",
            )

        with context.dependencies.session_factory() as session:
            row = session.scalar(
                select(RrugcStage3AnalysisModel).where(
                    RrugcStage3AnalysisModel.id == analysis_id,
                    RrugcStage3AnalysisModel.tenant_id == context.job.tenant_id,
                )
            )
            stage2 = session.scalar(
                select(RrugcStage2JobModel).where(
                    RrugcStage2JobModel.id == stage2_job_id,
                    RrugcStage2JobModel.tenant_id == context.job.tenant_id,
                )
            )
            if row is None or stage2 is None:
                return JobHandlerResult.non_retryable(
                    "stage3_analysis_not_found",
                    "Stage 3 analysis source was not found.",
                )
            if row.analysis_revision != revision:
                return JobHandlerResult.completed()
            if row.status in {"ready", "rejected"}:
                return JobHandlerResult.completed()
            if (
                stage2.status != "completed"
                or not stage2.output_remote_file_id
            ):
                return JobHandlerResult.non_retryable(
                    "stage3_stage2_output_not_ready",
                    "Stage 2 output is not ready for Stage 3 analysis.",
                )

            row.status = "analyzing"
            row.started_at = row.started_at or datetime.now(timezone.utc)
            row.last_error_code = None
            row.last_error_message = None
            session.commit()

            remote_file_id = stage2.output_remote_file_id
            content_type = stage2.output_content_type
            size_bytes = stage2.output_size_bytes

        storage = context.dependencies.storage_provider
        if storage is None:
            raise AnalysisImageError(
                "Managed storage is unavailable.",
                code="managed_storage_unavailable",
                retryable=True,
            )

        prepared = await AnalysisImagePreparer(storage).prepare(
            OpenStoredAssetInput(
                tenant_id=context.job.tenant_id,
                asset_id=f"rrugc-stage3:{analysis_id}",
                remote_file_id=remote_file_id,
                content_type=content_type,
                size_bytes=size_bytes,
            )
        )

        registry = context.dependencies.ai_provider_registry
        if registry is None:
            raise AiProviderUnavailableError("gemini")
        provider = registry.require("gemini")
        slot = scheduled_rrugc_gemini_slot(context.job)
        result = await provider.analyze_single(
            AiMetadataAnalysisInput(
                tenant_id=context.job.tenant_id,
                asset_id=stage2_job_id,
                prompt=stage3_analysis_prompt(),
                image_bytes=prepared.content,
                image_mime_type=prepared.mime_type,
                metadata_profile="rrugc_stage3_ugc_review",
                metadata_profile_version=STAGE3_ANALYSIS_VERSION,
                image_width=prepared.width,
                image_height=prepared.height,
                json_schema=Stage3UgcAnalysisDocument.model_json_schema(),
                analysis_id=analysis_id,
                preferred_model=(slot.model if slot else None),
                preferred_credential_provider=(
                    slot.credential_provider if slot else None
                ),
            )
        )
        document = Stage3UgcAnalysisDocument.model_validate(
            normalize_stage3_metadata(dict(result.metadata))
        )
        decision = evaluate_stage3(document)

        with context.dependencies.session_factory() as session:
            row = session.scalar(
                select(RrugcStage3AnalysisModel).where(
                    RrugcStage3AnalysisModel.id == analysis_id,
                    RrugcStage3AnalysisModel.tenant_id == context.job.tenant_id,
                )
            )
            if row is None or row.analysis_revision != revision:
                return JobHandlerResult.completed()
            row.status = decision.status
            row.people_count = document.people_count
            row.person_visible = document.person_visible
            row.hat_visible = document.hat_visible
            row.product_visible = document.product_visible
            row.embroidery_visible = document.embroidery_visible
            row.mobile_ugc_score = document.mobile_ugc_score
            row.photorealism_score = document.photorealism_score
            row.product_visibility_score = document.product_visibility_score
            row.review_fit_score = document.review_fit_score
            row.final_score = decision.final_score
            row.scene_type = document.scene_type
            row.framing_type = document.framing_type
            row.summary = document.summary
            row.reviewer_name = reviewer_name_for_analysis(analysis_id)
            row.star_rating = star_rating_for_analysis(analysis_id)
            row.review_text = review_text_for_analysis(document, analysis_id)
            row.review_generated_at = datetime.now(timezone.utc)
            row.evidence_json = list(document.evidence)
            row.reject_reasons_json = list(decision.reject_reasons)
            row.provider = result.provider
            row.model = result.model
            row.last_error_code = None
            row.last_error_message = None
            row.completed_at = datetime.now(timezone.utc)
            session.commit()

        context.logger.info(
            "rrugc_stage3_analysis_completed",
            extra={
                "analysis_id": analysis_id,
                "stage2_job_id": stage2_job_id,
                "tenant_id": context.job.tenant_id,
                "status": decision.status,
                "final_score": decision.final_score,
            },
        )
        return JobHandlerResult.completed()

    def _mark_error(
        self,
        context: JobHandlerContext,
        code: str,
        message: str,
    ) -> None:
        analysis_id = str(context.job.payload.get("analysis_id") or context.job.entity_id)
        try:
            with context.dependencies.session_factory() as session:
                row = session.scalar(
                    select(RrugcStage3AnalysisModel).where(
                        RrugcStage3AnalysisModel.id == analysis_id,
                        RrugcStage3AnalysisModel.tenant_id == context.job.tenant_id,
                    )
                )
                if row is None:
                    return
                row.status = "error"
                row.last_error_code = code[:100]
                row.last_error_message = message[:2000]
                session.commit()
        except Exception:
            context.logger.exception(
                "rrugc_stage3_analysis_error_state_failed",
                extra={"analysis_id": analysis_id},
            )

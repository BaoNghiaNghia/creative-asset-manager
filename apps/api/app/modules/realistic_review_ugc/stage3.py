def reviewer_name_for_analysis(analysis_id: str) -> str:
    digest = hashlib.sha256(analysis_id.encode("utf-8")).digest()
    first_name = REVIEWER_FIRST_NAMES[digest[0] % len(REVIEWER_FIRST_NAMES)]
    last_initial = chr(ord("A") + (digest[1] % 26))
    return f"{first_name} {last_initial}."


def star_rating_for_analysis(analysis_id: str) -> int:
    bucket = hashlib.sha256(("stars:" + analysis_id).encode("utf-8")).digest()[0]
    if bucket < 205:
        return 5
    if bucket < 248:
        return 4
    return 3



STAGE3_ANALYSIS_VERSION = "rrugc-stage3-ugc-v2"
STAGE3_JOB_TYPE = "rrugc_stage3_analyze"

class Stage3UgcAnalysisDocument(BaseModel):
    model_config = ConfigDict(extra="forbid")

    people_count: int = Field(ge=0, le=20)
    person_visible: bool
    hat_visible: bool
    product_visible: bool
    embroidery_visible: bool
    mobile_ugc_score: float = Field(ge=0.0, le=1.0)
    photorealism_score: float = Field(ge=0.0, le=1.0)
    product_visibility_score: float = Field(ge=0.0, le=1.0)
    review_fit_score: float = Field(ge=0.0, le=1.0)
    scene_type: str = Field(default="unknown", max_length=64)
    framing_type: str = Field(default="unknown", max_length=64)
    evidence: list[str] = Field(default_factory=list, max_length=6)
    summary: str = Field(min_length=1, max_length=500)
    review_text: str | None = Field(default=None, max_length=600)


_STAGE3_SCORE_FIELDS = (
    "mobile_ugc_score",
    "photorealism_score",
    "product_visibility_score",
    "review_fit_score",
)


def normalize_stage3_metadata(metadata: Mapping[str, object]) -> dict[str, object]:
    """Normalize common structured-output drift before strict validation."""
    allowed = set(Stage3UgcAnalysisDocument.model_fields)
    normalized: dict[str, object] = {
        key: value for key, value in metadata.items() if key in allowed
    }

    for key in _STAGE3_SCORE_FIELDS:
        value = normalized.get(key)
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            score = float(value)
            if 1.0 < score <= 10.0:
                score /= 10.0
            elif 10.0 < score <= 100.0:
                score /= 100.0
            normalized[key] = score

    summary = normalized.get("summary")
    if not isinstance(summary, str) or not summary.strip():
        normalized["summary"] = (
            "Visible image qualities were evaluated for realistic UGC review-card fit."
        )

    evidence = normalized.get("evidence")
    if isinstance(evidence, list) and len(evidence) > 6:
        normalized["evidence"] = evidence[:6]

    return normalized


def stage3_analysis_prompt() -> str:
    return """
You are evaluating a generated product lifestyle image for use in a realistic UGC customer-review card.
Return exactly one JSON object matching the supplied schema and no prose.

Evaluate only visible image qualities. Do not identify any person and do not infer age, ethnicity,
health, religion, politics, sexual orientation, or other sensitive traits.

The product is a hat/cap with a personalized embroidery design. Score:
- people_count / person_visible: whether at least one person is visibly present.
- hat_visible: whether a hat/cap is visibly present.
- product_visible: whether the featured product is sufficiently visible to understand what is reviewed.
- embroidery_visible: whether embroidery/design detail on the hat is visibly readable/recognizable.
- mobile_ugc_score: natural phone-photo / social UGC feel, not polished studio-ad composition.
- photorealism_score: plausible camera photograph appearance, anatomy, materials, lighting, shadows and edges.
- product_visibility_score: product prominence and clarity without requiring a close-up.
- review_fit_score: overall suitability as the hero image for a believable customer review card.

Do not penalize an image merely because it was generated by AI; judge the visible result.
A normal lifestyle crop is acceptable. Embroidery visibility is useful but not mandatory for approval.
Evidence must contain at most 6 short visible observations.

Also write review_text as 1-3 short, natural sentences in casual American English for a synthetic
customer-review card. It should sound like an ordinary hat buyer talking about everyday wear, fit,
style, or why they picked the design. Keep it specific enough to feel human, but only use details that
are visible or safely generic. Do not identify the visible person, infer demographic traits, or invent
shipping speed, customer service interactions, discounts, exact durability history, or other facts not
supported by the image. Vary both sentence count and opening style from one image to the next; do not
default to stock openings such as "Obsessed with...". Do not include a reviewer name or star rating
in review_text.
""".strip()


@dataclass(frozen=True, slots=True)
class Stage3Decision:
    status: str
    final_score: float
    reject_reasons: list[str]


def evaluate_stage3(document: Stage3UgcAnalysisDocument) -> Stage3Decision:
    reasons: list[str] = []
    if document.people_count < 1 or not document.person_visible:
        reasons.append("no_visible_person")
    if not document.hat_visible and not document.product_visible:
        reasons.append("product_not_visible")
    final_score = round(
        0.30 * document.review_fit_score
        + 0.25 * document.mobile_ugc_score
        + 0.25 * document.product_visibility_score
        + 0.20 * document.photorealism_score,
        4,
    )
    return Stage3Decision(
        status="ready" if not reasons else "rejected",
        final_score=final_score,
        reject_reasons=reasons,
    )


